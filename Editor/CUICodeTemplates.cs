    /// </summary>
    internal sealed class CUIPanelCodeInfo
    {
        /// <summary>单个绑定字段信息。</summary>
        public sealed class BindField
        {
            /// <summary>字段名（默认节点名）。</summary>
            public string FieldName;

            /// <summary>组件类型名（如 UnityEngine.UI.Button）。</summary>
            public string ComponentType;

            /// <summary>字段注释（CBind.Comment）。</summary>
            public string Comment;

            /// <summary>是否为独立 CUIElement（生成独立脚本）。</summary>
            public bool IsElement;
        }

        public System.Collections.Generic.List<BindField> Fields = new System.Collections.Generic.List<BindField>();
    }

