        /// <summary>生成 Designer partial（字段 + ClearUIComponents，每次覆盖）。</summary>
        public static string PanelDesignerScript(string panelName, string ns, CUIPanelCodeInfo info)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// 此文件由 CoffeeBean UI 代码生成器自动生成，请勿手动修改（重新生成会覆盖）。");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine();
            sb.AppendLine("using UnityEngine;");
            sb.AppendLine("using CoffeeBean;");
            sb.AppendLine();
            sb.AppendLine($"namespace {ns}");
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>自动生成：字段绑定与清理（partial 主脚本见 {panelName}.cs）。</summary>");
            sb.AppendLine($"    public partial class {panelName}");
            sb.AppendLine("    {");
            sb.AppendLine($"        public const string Name = \"{panelName}\";");
            sb.AppendLine();

            foreach (var field in info.Fields)
            {
                if (!string.IsNullOrEmpty(field.Comment))
                {
                    sb.AppendLine("        /// <summary>" + field.Comment + "</summary>");
                }
                sb.AppendLine($"        [SerializeField] public {field.ComponentType} {field.FieldName};");
            }

            sb.AppendLine();
            sb.AppendLine("        protected override void OnBeforeDestroy()");
            sb.AppendLine("        {");
            sb.AppendLine("            ClearUIComponents();");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        private void ClearUIComponents()");
            sb.AppendLine("        {");
            foreach (var field in info.Fields)
            {
                sb.AppendLine($"            {field.FieldName} = null;");
            }
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

